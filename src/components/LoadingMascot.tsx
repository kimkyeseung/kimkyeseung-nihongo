/**
 * LLM 응답 대기 등에 쓰는 로딩 인디케이터 — 로고의 고양이가 통통 튀며 기다린다.
 *
 * 크기는 예전 🗻(text-xl)와 같은 한 줄 높이(28px)다. 이 컴포넌트는 스트리밍 직전 말풍선·
 * 바텀시트처럼 **높이가 바뀌면 화면이 튀는 자리**에 많이 들어가서(연습해보기 시트의 min-h 등),
 * 튀어 오르는 것도 그림자도 전부 transform/absolute로만 움직이고 레이아웃 높이는 그대로 둔다.
 */
function LoadingMascot({ label }: { label?: string }) {
  // "." -> ".." -> "..." -> "."로 반복되는 온점 애니메이션. 프레임마다 길이가 달라져서
  // 옆 글자가 들썩이지 않도록 고정폭(w-4)에 왼쪽 정렬로 렌더링한다.
  const [dotIndex, setDotIndex] = useState(0);
  // 움직임 줄이기 설정이면 고양이는 가만히 앉아 있고 온점만 바뀐다.
  const reduceMotion = useReducedMotion() ?? false;

  useEffect(() => {
    const timer = setInterval(() => {
      setDotIndex((i) => (i + 1) % DOT_FRAMES.length);
    }, 400);
    return () => clearInterval(timer);
  }, []);

  const hop = { duration: HOP_SECONDS, repeat: Infinity, ease: "easeInOut" as const };

  return (
    <div className="flex items-center gap-2 text-gray-400">
      <span className="relative inline-block h-7 w-7 shrink-0">
        {/* 바닥 그림자 — 뛰어오를수록 작고 옅어진다. */}
        <motion.span
          aria-hidden
          className="absolute -bottom-1 left-1/2 h-1 w-4 -translate-x-1/2 rounded-full bg-gray-200"
          animate={reduceMotion ? undefined : { scaleX: [1, 0.6, 1], opacity: [0.7, 0.35, 0.7] }}
          transition={hop}
        />
        {/* 착지할 때 살짝 납작해졌다가 튀어 오르고, 오를 때마다 고개를 번갈아 갸웃한다. */}
        <motion.span
          className="absolute inset-0 block"
          style={{ transformOrigin: "50% 100%" }}
          animate={
            reduceMotion
              ? undefined
              : {
                  y: [0, -7, 0, -7, 0],
                  scaleY: [0.9, 1.05, 0.9, 1.05, 0.9],
                  scaleX: [1.08, 0.97, 1.08, 0.97, 1.08],
                  rotate: [0, -8, 0, 8, 0],
                }
          }
          transition={{ ...hop, duration: HOP_SECONDS * 2 }}
        >
          <CatFace animateEars={!reduceMotion} />
        </motion.span>
      </span>
      <span className="inline-block w-4 text-left font-bold">{DOT_FRAMES[dotIndex]}</span>
      {label && <span className="text-sm">{label}</span>}
    </div>
  );
}

export default LoadingMascot;
